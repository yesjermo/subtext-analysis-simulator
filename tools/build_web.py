#!/usr/bin/env python3
"""Bundle decoder data and demo chats into web/data.js.

Run after editing anything in subtext/data/ or examples/.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA_NAMES = ("slang", "emoji", "signals", "playbook", "screenshot")


def main() -> None:
    data = {
        name: json.loads(
            (ROOT / "subtext" / "data" / f"{name}.json").read_text(encoding="utf-8")
        )
        for name in DATA_NAMES
    }
    demos = json.loads((ROOT / "examples" / "demos.json").read_text(encoding="utf-8"))
    for demo in demos:
        demo["text"] = (ROOT / demo["file"]).read_text(encoding="utf-8")
        demo["filename"] = Path(demo["file"]).name
    data["demos"] = demos

    out = ROOT / "web" / "data.js"
    contents = (
        "// Generated by tools/build_web.py from subtext/data/ and examples/. "
        "Do not edit by hand.\n"
        f"window.SUBTEXT_DATA = {json.dumps(data, ensure_ascii=False, indent=2)};\n"
    )
    out.write_text(contents, encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
